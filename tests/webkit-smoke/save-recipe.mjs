// Guard key so an addInitScript re-fire (Playwright runs it on every navigation,
// including reload) does NOT re-seed and clobber the game's own persisted save —
// that is what lets the "refresh persists earth=true" assertion be meaningful.
export const SEED_SENTINEL = '__webkit_smoke_seeded';

// Turn a freshly-generated, valid save seed into the test fixture.
//   seed:   { [localStorageKey]: stringValue }  (snapshot of a fresh game)
//   def:    defaultSpace() object from /space/domain.mjs
//   coins:  target coin balance
export function buildSeed(seed, def, coins) {
  const save = JSON.parse(seed[SAVE_KEY]);
  delete save.milestones;                                  // old progressed save, no ledger
  for (const shop of save.shops) Object.assign(shop, { open: true, lv: 35, emp: 1 });
  save.space = JSON.parse(JSON.stringify(def));
  save.space.ended = true;                                 // received the reply -> earth unlockable
  save.space.earth = false;
  save.coins = coins;
  save.lastSeen = save.maxSeen = Date.now();
  const out = { ...seed };
  out[SAVE_KEY] = JSON.stringify(save);
  delete out[TAB_LOCK_KEY];                                // drop the writer lock from the snapshot
  return out;
}
